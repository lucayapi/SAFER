"""Build full or Qwen3-BTP pilot recipes retaining matched-run embeddings.

Original checkpoints and adapted embeddings were intentionally discarded. This
recipe reproduces the selected training pipelines in a new directory and keeps
the representations and predictions generated by the *same* fitted model.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from replication.runner import _model_config, load_replication_config, training_seeds

RECIPES = {
    "multilingual": ROOT / "output/replication_recipes/backbone_source_factorial.yaml",
    "camembert": ROOT / "output/replication_recipes/camembert_source_factorial.yaml",
    "camembert_repair": ROOT / "output/replication_recipes/camembert_metallurgie_repair.yaml",
}
METHODS = ("cross_entropy", "supcon", "softtriple")
SOURCES = ("btp", "metallurgie")
BACKBONES = ("qwen3", "multilingual_e5_large", "camembert")


def build_recipe(scope: str = "all") -> dict:
    if scope not in {"all", "qwen3_btp"}:
        raise ValueError(f"Unknown adapted-geometry scope: {scope}")
    configs = {name: load_replication_config(path) for name, path in RECIPES.items()}
    seeds = training_seeds(configs["multilingual"])
    if len(seeds) != 5 or any(training_seeds(cfg) != seeds for cfg in configs.values()):
        raise ValueError("Original campaigns do not share the expected five seeds")
    models = {}
    backbones = ("qwen3",) if scope == "qwen3_btp" else BACKBONES
    sources = ("btp",) if scope == "qwen3_btp" else SOURCES
    for backbone in backbones:
        for source in sources:
            origin = "camembert_repair" if (backbone, source) == ("camembert", "metallurgie") else (
                "camembert" if backbone == "camembert" else "multilingual")
            config = configs[origin]
            for method in METHODS:
                model_id = f"{backbone}_{source}_{method}"
                spec = _model_config(config, model_id)
                if spec["runner"] == "supervised_macro_ft":
                    spec.setdefault("overrides", {}).setdefault("exports", {})["save_btp_embeddings"] = True
                original_root = Path(config["output_root"])
                if not original_root.is_absolute():
                    original_root = ROOT / original_root
                for seed in seeds:
                    manifest = original_root / model_id / f"seed_{seed}" / "run_manifest.json"
                    if not manifest.is_file() or json.loads(manifest.read_text(encoding="utf-8")).get("status") != "complete":
                        raise FileNotFoundError(f"Completed historical run missing: {manifest}")
                models[model_id] = spec
    expected_models = 3 if scope == "qwen3_btp" else 18
    if len(models) != expected_models:
        raise AssertionError(f"Expected {expected_models} model configurations, got {len(models)}")
    base = configs["multilingual"]
    return {
        "output_root": "output/adapted_geometry_pilot/runs" if scope == "qwen3_btp" else "output/adapted_geometry/runs",
        "storage": {"cleanup_after_completion": True, "keep_final_checkpoint": False,
                    "keep_embeddings": True, "max_parallel_seeds": 4},
        "training": dict(base["training"]),
        "models": models,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", default="output/replication_recipes/adapted_geometry.yaml")
    parser.add_argument("--scope", choices=("all", "qwen3_btp"), default="all")
    args = parser.parse_args()
    output = Path(args.output)
    if not output.is_absolute():
        output = ROOT / output
    recipe = build_recipe(args.scope)
    content = yaml.safe_dump(recipe, sort_keys=False, allow_unicode=True)
    output.parent.mkdir(parents=True, exist_ok=True)
    if output.is_file() and output.read_text(encoding="utf-8") != content:
        raise FileExistsError(f"Existing recipe differs; inspect before replacing: {output}")
    if not output.is_file():
        output.write_text(content, encoding="utf-8")
    print(f"{output}: {len(recipe['models'])} models x 5 seeds = {5 * len(recipe['models'])} adapted refits")


if __name__ == "__main__":
    main()
